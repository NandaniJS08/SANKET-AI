// Helper for smooth linear color interpolation
function hexToRgb(hex) {
  const bigint = parseInt(hex.replace("#", ""), 16);
  return [(bigint >> 16) & 255, (bigint >> 8) & 255, bigint & 255];
}

function rgbToHex(r, g, b) {
  return `#${((1 << 24) + (r << 16) + (g << 8) + b).toString(16).slice(1).toUpperCase()}`;
}

function interpolateHex(color1, color2, t) {
  const [r1, g1, b1] = hexToRgb(color1);
  const [r2, g2, b2] = hexToRgb(color2);
  const r = Math.round(r1 + t * (r2 - r1));
  const g = Math.round(g1 + t * (g2 - g1));
  const b = Math.round(b1 + t * (b2 - b1));
  return rgbToHex(r, g, b);
}

// Compute accurate Choropleth Color matching the official MoSPI portal (0 = Light Beige Cream to 182 = Deep Maroon)
export function getChoroplethColor(count, max = 182) {
  const clamped = Math.max(0, Math.min(max, count || 0));
  
  // Official MoSPI Color Key Stops (0, 46, 91, 137, 182)
  const stops = [
    { val: 0, color: "#FBF3E3" },    // Light Beige Cream
    { val: 46, color: "#F5D2BE" },   // Soft Peach
    { val: 91, color: "#E59E8D" },   // Warm Terracotta
    { val: 137, color: "#BA4746" },  // Crimson Rose
    { val: 182, color: "#9E2D2F" }   // Deep Maroon
  ];

  for (let i = 0; i < stops.length - 1; i++) {
    const s1 = stops[i];
    const s2 = stops[i + 1];
    if (clamped >= s1.val && clamped <= s2.val) {
      const t = (clamped - s1.val) / (s2.val - s1.val);
      return interpolateHex(s1.color, s2.color, t);
    }
  }

  return "#9E2D2F";
}

// Fallback resolver for names (handles aliases like "Jammu & Kashmir" vs "Jammu and Kashmir")
export function getStateData(stateNameOrId) {
  if (!stateNameOrId) return stateProjectsData["Rajasthan"];
  
  if (stateProjectsData[stateNameOrId]) {
    return stateProjectsData[stateNameOrId];
  }

  const normalized = stateNameOrId.toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]/g, "");
  
  for (const key of Object.keys(stateProjectsData)) {
    const item = stateProjectsData[key];
    const keyNorm = key.toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]/g, "");
    const idNorm = item.id.toLowerCase();
    const codeNorm = item.code.toLowerCase();
    
    if (keyNorm === normalized || idNorm === normalized || codeNorm === normalized) {
      return item;
    }
  }

  return {
    id: "IN",
    code: "in",
    name: stateNameOrId,
    projectCount: 15,
    originalCost: 45000.00,
    revisedCost: 51000.00,
    expenditure: 36000.00,
    completedDuringMonth: 0,
    newlyAdded: 0,
    highRiskCount: 2,
    majorSectors: ["General Infrastructure"]
  };
}
